#!/usr/bin/env node
// Copies the platform-neutral lib/ files from the web app into src/shared/.
//   npm run sync:shared   -> write the copies
//   npm run check:shared  -> exit 1 if any copy differs from its source
// The web repo is the single source of truth; src/shared/ is never edited here.
import { access, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = path.resolve(root, "../egx-api-fe/src/app/lib");
const TARGET_DIR = path.join(root, "src/shared");

const SHARED_FILES = [
  "api.ts",
  "apiConfig.ts",
  "auth.ts",
  "constants.ts",
  "positions.ts",
  "riskBands.ts",
  "theme.ts",
  "types.ts",
  "learn.ts",
  "learnVisuals.ts",
  "learnWidgets.ts",
  "learnLive.ts",
  "curriculum.ts",
];

const header = (file) =>
  `// GENERATED by scripts/sync-shared.mjs from egx-api-fe/src/app/lib/${file}.\n` +
  `// Do not edit here: change the web repo, then run \`npm run sync:shared\`.\n`;

const check = process.argv.includes("--check");

if (check && process.env.SKIP_SHARED_CHECK === "1") {
  console.log("check:shared skipped (SKIP_SHARED_CHECK=1)");
  process.exit(0);
}

try {
  await access(SOURCE_DIR);
} catch {
  console.error(
    `Web repo not found at ${SOURCE_DIR}.\n` +
      "Clone egx-api-fe beside this repo, or set SKIP_SHARED_CHECK=1 on a build machine."
  );
  process.exit(1);
}

await mkdir(TARGET_DIR, { recursive: true });
const problems = [];

for (const file of SHARED_FILES) {
  const expected = header(file) + (await readFile(path.join(SOURCE_DIR, file), "utf8"));
  const target = path.join(TARGET_DIR, file);
  const actual = await readFile(target, "utf8").catch(() => null);
  if (actual === expected) continue;
  if (check) problems.push(`${file} differs from egx-api-fe`);
  else {
    await writeFile(target, expected);
    console.log(`synced ${file}`);
  }
}

for (const file of await readdir(TARGET_DIR)) {
  if (!SHARED_FILES.includes(file)) problems.push(`${file} is in src/shared but not in SHARED_FILES`);
}

if (problems.length) {
  console.error(`src/shared is out of date:\n  ${problems.join("\n  ")}\nRun npm run sync:shared and commit.`);
  process.exit(1);
}
if (check) console.log(`check:shared OK (${SHARED_FILES.length} files)`);
